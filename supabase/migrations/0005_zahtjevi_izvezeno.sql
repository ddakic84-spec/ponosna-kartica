-- Вријеме када је захтјев ушао у неки „нови" Excel. Празно = још није преузет.
-- Сви захтјеви преузети у истом кораку добијају исту вриједност (то је једна
-- „група" преузимања).
alter table zahtjevi
  add column if not exists izvezeno timestamptz;

create index if not exists zahtjevi_izvezeno_idx
  on zahtjevi (izvezeno);
