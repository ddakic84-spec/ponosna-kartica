// Свођење имена и бар кода на облик за ПОРЕЂЕЊЕ (никад за приказ).
//
// Проблем у стварним подацима: нека имена садрже латинична слова која
// изгледају исто као ћирилична (нпр. „Aњушка" — прво слово латинично „A").
// Зато при поређењу свако такво слово претварамо у ћирилично, скидамо
// вишак размака и све претварамо у мала слова. Исто радимо и са уносом
// грађанина и са оним што стоји у бази.

const LAT_U_CIR: Record<string, string> = {
  A: "А", a: "а",
  B: "В",
  C: "С", c: "с",
  E: "Е", e: "е",
  H: "Н",
  J: "Ј", j: "ј",
  K: "К", k: "к",
  M: "М",
  O: "О", o: "о",
  P: "Р", p: "р",
  T: "Т",
  X: "Х", x: "х",
  Y: "У", y: "у",
};

export function normalizujIme(ime: string): string {
  const uCirilicu = Array.from((ime ?? "").trim())
    .map((ch) => LAT_U_CIR[ch] ?? ch)
    .join("")
    .toLowerCase();
  // Ријечи се сортирају — тако „Тања Бановић" и „Бановић Тања" дају исти резултат
  // (неке улазне листе имају редослијед Презиме Име).
  return uCirilicu
    .split(/\s+/)
    .filter(Boolean)
    .sort()
    .join(" ");
}

// Само цифре (скида размаке, цртице, слова…).
export function samoCifre(vrijednost: string): string {
  return (vrijednost ?? "").replace(/[^0-9]/g, "");
}
